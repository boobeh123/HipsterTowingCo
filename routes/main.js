const express = require('express')
const router = express.Router()
const authController = require('../controllers/auth') 
const homeController = require('../controllers/home')
const onboardController = require('../controllers/onboard')
const passwordResetController = require('../controllers/reset')
const privacyController = require('../controllers/privacy')
const termController = require('../controllers/terms')
const learnController = require('../controllers/learn')
const inspectionController = require('../controllers/inspection')
const dashboardController = require('../controllers/dashboard')
const profileController = require('../controllers/profile')
const { uploadProfilePhoto } = require('../middleware/multer')
const { ensureAuth, ensureAuthApi, ensureOnboarding } = require('../middleware/auth')
const { authLimiter, passwordResetLimiter, counterLimiter, inspectionSaveLimiter, signOffLimiter, photoUploadLimiter, passwordChangeLimiter, exportLimiter } = require('../middleware/rateLimiters')
const { validateLogin, validateSignup, validateForgot, validateReset, validateOnboard, validateInspection, validateProfileName, validateProfilePassword, validateDashboardQuery, validatePrivacyNotice, validateCertification, validateAcknowledgment } = require('../middleware/validators')

router.get('/', homeController.getIndex)
router.get('/dashboard', ensureAuth, validateDashboardQuery, dashboardController.getDashboard)
router.get('/dashboard/export', ensureAuth, exportLimiter, validateDashboardQuery, dashboardController.exportCsv)
router.get('/inspections/:id', ensureAuthApi, inspectionController.getInspection)
router.post('/inspections/count', counterLimiter, homeController.postInspectionCount)
router.post('/inspections', ensureAuthApi, inspectionSaveLimiter, validateInspection, inspectionController.postInspection)
router.delete('/inspections/:id', ensureAuth, inspectionController.deleteInspection)

// Repair sign-offs added to a saved report from the dashboard (fetch, JSON)
router.put('/inspections/:id/certification', ensureAuthApi, signOffLimiter, validateCertification, inspectionController.putCertification)
router.delete('/inspections/:id/certification', ensureAuthApi, signOffLimiter, inspectionController.deleteCertification)
router.put('/inspections/:id/acknowledgment', ensureAuthApi, signOffLimiter, validateAcknowledgment, inspectionController.putAcknowledgment)

router.get('/onboard', ensureOnboarding, onboardController.getOnboard)
router.post('/onboard', ensureOnboarding, validateOnboard, onboardController.postOnboard)

router.get('/profile', ensureAuth, profileController.getProfile)
router.post('/profile/photo', ensureAuth, photoUploadLimiter, uploadProfilePhoto, profileController.updatePhoto)
router.post('/profile/name', ensureAuth, validateProfileName, profileController.updateName)
router.post('/profile/password', ensureAuth, passwordChangeLimiter, validateProfilePassword, profileController.updatePassword)
router.delete('/profile/delete', ensureAuth, profileController.deleteAccount)

router.get('/login', authController.getLogin)
router.post('/login', authLimiter, validateLogin, authController.postLogin)
router.post('/logout', authController.postLogout)
router.get('/signup', authController.getSignup)
router.post('/signup', authLimiter, validateSignup, authController.postSignup)
router.get('/forgot', passwordResetController.getPasswordReset)
router.post('/forgot', passwordResetLimiter, validateForgot, passwordResetController.postPasswordReset)
router.get('/reset/:token', passwordResetController.getRecoverPassword)
router.post('/reset/:token', passwordResetLimiter, validateReset, passwordResetController.postRecoverPassword)

router.get('/privacy', privacyController.getPrivacy)
router.post('/privacy/notice', ensureAuth, validatePrivacyNotice, privacyController.postNoticeSeen)
router.get('/terms', termController.getTerms)

router.get('/learn', learnController.getLearn)
router.get('/learn/dvir', learnController.getDvirGuide)
router.get('/learn/pre-trip', learnController.getPreTripGuide)


module.exports = router
